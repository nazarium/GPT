import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(new URL('../../../package.json', import.meta.url));
const wrangler = createRequire(require.resolve('wrangler/package.json'));
export const {Miniflare, convertV4MiniflareOptions} = wrangler('miniflare');
const original = await readFile(new URL('../apps-script/Dialog.gs', import.meta.url), 'utf8');
const generated = await readFile(new URL('src/dialog.generated.mjs', import.meta.url), 'utf8');
assert.equal(generated, '// Generated by build-dialog.mjs; edit apps-script/Dialog.gs.\n' + original + '\nexport {acpReducer_, acpEmpty_};\n', 'Rebuild dialogue module before testing');
const result = await require('esbuild').build({entryPoints: [fileURLToPath(new URL('src/worker.mjs', import.meta.url))], bundle: true, write: false, format: 'esm', platform: 'browser', external: ['cloudflare:workers']});
export const script = result.outputFiles[0].text;
